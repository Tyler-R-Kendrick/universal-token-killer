import type { BenchmarkProvenance } from './data.js';
import type { ArmResult, BenchmarkResult } from './harness.js';

const DEFAULT_DISCLAIMER =
  'Self-authored deterministic self-comparison: competitor arms are configured models of each ' +
  "technique run against the same benchmark data, not the vendors' live systems. Token counts use " +
  'a coarse `ceil(len/4)` estimate. Quality is scored by the reference judge (fact retention + noise ' +
  'exclusion); swap in a model judge via the harness `configureModel` hook for semantic grading.';

/** Signed percentage change in visible tokens vs the baseline arm. */
function changeVsBaseline(tokens: number, baselineTokens: number): string {
  if (baselineTokens === 0) return '—';
  const pct = Math.round((tokens / baselineTokens - 1) * 100);
  return pct === 0 ? '0%' : `${pct > 0 ? '+' : '−'}${Math.abs(pct)}%`;
}

function baselineOf(result: BenchmarkResult): ArmResult | undefined {
  return result.arms.find((arm) => arm.arm === 'baseline');
}

/** The leaderboard: one row per technique (baseline + competitors + UTK), 3 columns. */
export function renderLeaderboard(result: BenchmarkResult): string[] {
  const baselineTokens = baselineOf(result)?.totals.visibleTokens ?? 0;
  const ranked = [...result.arms].sort((a, b) => b.totals.visibleTokens - a.totals.visibleTokens);
  return [
    '| Technique | Tokens | Change |',
    '| --- | ---: | ---: |',
    ...ranked.map((arm) => `| ${escapeCell(arm.label)} | ${arm.totals.visibleTokens} | ${changeVsBaseline(arm.totals.visibleTokens, baselineTokens)} |`)
  ];
}

/** Render the whole benchmark as one leaderboard-first results doc. */
export function renderBenchmarkMarkdown(result: BenchmarkResult, provenance?: BenchmarkProvenance | null): string {
  const ranked = [...result.arms].sort((a, b) => b.totals.visibleTokens - a.totals.visibleTokens);
  const lines = [
    '# Tool-output compaction benchmark',
    '',
    `Three-plus concurrent arms over the same ${result.cases} cases: **baseline** (raw output), each **competitor**, and **UTK** (raw persisted off-context, recoverable handle in chat).`,
    '',
    `> ${provenance?.disclaimer ?? DEFAULT_DISCLAIMER}`,
    '',
    '## Leaderboard',
    '',
    'Model-visible tokens (lower is better). Change is vs the baseline arm.',
    '',
    ...renderLeaderboard(result),
    '',
    '## Quality',
    '',
    'Every arm is gated on fact retention — a dropped required fact zeroes that case.',
    '',
    '| Technique | Facts kept | Avg quality | Avg composite |',
    '| --- | ---: | ---: | ---: |',
    ...ranked.map((arm) => `| ${escapeCell(arm.label)} | ${arm.totals.passed}/${arm.totals.cases} | ${arm.totals.avgQuality} | ${arm.totals.avgComposite} |`),
    '',
    '## Per-case visible tokens',
    '',
    ...renderPerCase(result),
    ''
  ];
  if (provenance) {
    lines.push(...renderProvenance(provenance), '');
  }
  lines.push('Generated by `npm run evals --workspace @utk/evals`.');
  return `${lines.join('\n')}\n`;
}

function renderPerCase(result: BenchmarkResult): string[] {
  const baseline = baselineOf(result);
  if (!baseline) return [];
  const columns = result.arms;
  const header = `| Case | Category | ${columns.map((arm) => escapeCell(shortLabel(arm))).join(' | ')} |`;
  const divider = `| --- | --- | ${columns.map(() => '---:').join(' | ')} |`;
  const rows = baseline.cases.map((_, index) => {
    const name = baseline.cases[index]!.name;
    const category = baseline.cases[index]!.category;
    const cells = columns.map((arm) => String(arm.cases[index]?.visibleTokens ?? ''));
    return `| ${escapeCell(name)} | ${escapeCell(category)} | ${cells.join(' | ')} |`;
  });
  return [header, divider, ...rows];
}

function renderProvenance(provenance: BenchmarkProvenance): string[] {
  return [
    '## Provenance',
    '',
    `- Origin: ${provenance.origin} (${provenance.authored_by})`,
    `- License: ${provenance.license} · version ${provenance.version}`,
    `- ${provenance.description}`,
    '',
    '### Related public benchmarks',
    '',
    'Referenced as task-category analogs so readers can anchor the kinds of tool output measured here — not data sources, and not scored on:',
    '',
    ...provenance.related_benchmarks.map((bench) => `- [${bench.name}](${bench.url})${bench.org ? ` (${bench.org})` : ''} — ${bench.note ?? bench.relation}`)
  ];
}

function shortLabel(arm: ArmResult): string {
  if (arm.arm === 'baseline') return 'baseline';
  if (arm.arm === 'utk') return 'UTK';
  return arm.competitor;
}

function escapeCell(value: string): string {
  return value.replaceAll('|', '\\|');
}
