import type { ArmResult, ComparisonResult } from './harness.js';

const DISCLAIMER =
  'Self-authored deterministic self-comparison: competitor arms are configured models of each ' +
  "technique run against the same benchmark data, not the vendors' live systems. Token counts use " +
  'a coarse `ceil(len/4)` estimate. Quality is scored by the reference judge (fact retention + noise ' +
  'exclusion); swap in a model judge via the harness `configureModel` hook for semantic grading.';

/** Render one comparison (baseline / competitor / UTK) as a benchmark-results markdown doc. */
export function renderComparisonMarkdown(result: ComparisonResult): string {
  const baseline = result.arms.baseline;
  const competitor = result.arms.competitor;
  const utk = result.arms.utk;
  const lines = [
    `# ${result.label} vs UTK — ${result.benchmark} benchmark`,
    '',
    result.description,
    '',
    `> ${DISCLAIMER}`,
    '',
    '## Summary',
    '',
    '| Arm | Cases | Facts kept | Visible tokens | Saved vs raw | Avg ratio | Avg quality | Avg composite |',
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
    summaryRow(baseline),
    summaryRow(competitor),
    summaryRow(utk),
    '',
    '## Per-case visible tokens',
    '',
    `| Case | Category | Baseline | ${escapeCell(result.label)} | UTK | UTK saved |`,
    '| --- | --- | ---: | ---: | ---: | ---: |',
    ...result.cases > 0
      ? baseline.cases.map((_, index) => caseRow(result, index))
      : [],
    '',
    'Generated by `npm run evals --workspace @utk/evals`.'
  ];
  return `${lines.join('\n')}\n`;
}

/** Render the cross-competitor aggregate summary. */
export function renderSummaryMarkdown(results: ComparisonResult[]): string {
  const lines = [
    '# Benchmark Summary',
    '',
    'Aggregate view of the tool-output compaction benchmark: the same benchmark data run through the same',
    'harness against each competitor, with three concurrent arms (baseline, competitor, UTK).',
    '',
    `> ${DISCLAIMER}`,
    '',
    '## Current Results',
    '',
    '| Competitor | Cases | Baseline tok | Competitor tok | UTK tok | UTK vs competitor | UTK facts | Report |',
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |',
    ...results.map((result) => {
      const competitor = result.arms.competitor;
      const utk = result.arms.utk;
      const ratio = competitor.totals.visibleTokens === 0
        ? '—'
        : `${Math.round((1 - utk.totals.visibleTokens / competitor.totals.visibleTokens) * 100)}% fewer`;
      return `| ${escapeCell(result.label)} | ${result.cases} | ${result.arms.baseline.totals.visibleTokens} | ${competitor.totals.visibleTokens} | ${utk.totals.visibleTokens} | ${ratio} | ${utk.totals.passed}/${utk.totals.cases} | [report](${result.competitor}-benchmark-results.md) |`;
    }),
    '',
    '## Interpretation',
    '',
    '- **Baseline** reads the full tool output — maximum tokens, keeps every fact, keeps all the noise.',
    '- **Competitor** arms compact into the chat context: they cut tokens but pay for what survives and can shed relevant facts.',
    '- **UTK** persists the raw output off-context and surfaces a recoverable handle, so it keeps every fact at a fraction of the visible tokens.',
    '',
    '## Related benchmarks',
    '',
    '- LeanCTX Copilot context-runtime benchmark: [leanctx-copilot-benchmark-results.md](leanctx-copilot-benchmark-results.md).',
    '',
    '## Update Rules',
    '',
    '- Regenerate with `npm run evals --workspace @utk/evals`; it rewrites `results/*.json`, the suite YAML, and these docs together.',
    '- Never hand-edit the numbers — they are derived from `packages/evals/data/*.jsonl`.'
  ];
  return `${lines.join('\n')}\n`;
}

function summaryRow(arm: ArmResult): string {
  const t = arm.totals;
  return `| ${escapeCell(arm.label)} | ${t.cases} | ${t.passed}/${t.cases} | ${t.visibleTokens} | ${t.savedTokens} | ${t.avgRatio} | ${t.avgQuality} | ${t.avgComposite} |`;
}

function caseRow(result: ComparisonResult, index: number): string {
  const base = result.arms.baseline.cases[index]!;
  const comp = result.arms.competitor.cases[index]!;
  const utk = result.arms.utk.cases[index]!;
  const saved = base.visibleTokens === 0 ? 0 : Math.round((1 - utk.visibleTokens / base.visibleTokens) * 100);
  return `| ${escapeCell(base.name)} | ${escapeCell(base.category)} | ${base.visibleTokens} | ${comp.visibleTokens} | ${utk.visibleTokens} | ${saved}% |`;
}

function escapeCell(value: string): string {
  return value.replaceAll('|', '\\|');
}
